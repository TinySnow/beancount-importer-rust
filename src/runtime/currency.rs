//! 币种分类辅助模块。
//!
//! 该模块提供运行时共享的币种判定逻辑，当前主要用于：
//! - lot 成本补全阶段区分“证券持仓分录”和“现金分录”；
//! - 逐笔盈亏（PnL）阶段识别可作为现金计量基础的法币分录。
//!
//! 该模块仅负责业务分类，不涉及汇率换算与金额精度处理。

/// 判断给定代码是否应视为“法币现金”。
///
/// 当返回 `true` 时，上游逻辑通常会将该币种按现金类分录处理；
/// 当返回 `false` 时，通常按证券或其他非现金资产处理。
///
/// # 参数
/// - `currency`：币种或商品代码（例如 `CNY`、`USD`、`SEC_159915`）。
///
/// # 返回值
/// - `true`：属于法币现金白名单；
/// - `false`：不在白名单内。
pub(crate) fn is_fiat_currency(currency: &str) -> bool {
    matches!(
        currency,
        "CNY" | "USD" | "HKD" | "EUR" | "JPY" | "GBP" | "SGD" | "CHF" | "AUD" | "CAD"
    )
}
